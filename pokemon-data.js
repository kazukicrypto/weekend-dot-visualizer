function drawSprite(ctx, sprite, x, y, scale) {
  const lines = sprite.split('\n').filter(l => l.length > 0);
  for (let r = 0; r < lines.length; r++) {
    for (let c = 0; c < lines[r].length; c++) {
      const ch = lines[r][c];
      const col = PAL[ch];
      if (col) {
        ctx.fillStyle = col;
        ctx.fillRect(x + c * scale, y + r * scale, scale, scale);
      }
    }
  }
}

