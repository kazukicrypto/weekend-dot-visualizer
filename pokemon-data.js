const MAP_LINES = MAP_RAW.split('\n').filter(l => l.length > 0);
const MAP_W = MAP_LINES[0].length;
const MAP_H = MAP_LINES.length;
function tileAt(tx, ty) {
  if (tx < 0 || ty < 0 || tx >= MAP_W || ty >= MAP_H) return '#';
  const row = MAP_LINES[ty];
  return (row && row[tx]) || '#';
}

